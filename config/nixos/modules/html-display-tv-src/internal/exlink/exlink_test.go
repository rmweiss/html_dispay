package exlink

import "testing"

func TestFrameChecksum(t *testing.T) {
 cases:=[]struct{got,want string}{
  {string(Frame(0x08,0x22,0x00,0x00,0x00,0x01)),string([]byte{0x08,0x22,0,0,0,1,0xd5})},
  {string(Frame(0x08,0x22,0xf0,0x0a,0,0)),string([]byte{0x08,0x22,0xf0,0x0a,0,0,0xdc})},
  {string(Frame(0x08,0x22,0x0a,0,5,3)),string([]byte{0x08,0x22,0x0a,0,5,3,0xc4})},
 }
 for _,tc:=range cases{if tc.got!=tc.want{t.Fatalf("frame mismatch %x vs %x",tc.got,tc.want)}}
}
